# Sampling from logits generated by the device, with temperature parameter
def sample_from_logits(logits, temperature=1.0):

    scaled_logits = logits / temperature
    probs = F.softmax(scaled_logits, dim=-1)
    B, N, C = probs.shape

    samples = torch.multinomial(probs.view(-1, C), num_samples=1)
    return samples.view(B, N), probs.view(B, N, C)

# If the graph sampled by the decoder is disconnected (multiple separate components), 
# force connectivity by adding the minimum number of edges necessary to merge all the components into a single connected graph, 
# respecting the valence constraints.
def enforce_connectivity(nodes_row, edges_row, edge_probs_row):
    active = [i for i in range(9) if nodes_row[i] != 0]
    if len(active) <= 1:
        return edges_row

    # Construction of the current graph to find the components
    G_existing = nx.Graph()
    G_existing.add_nodes_from(active)
    for i in active:
        for j in active:
            if i < j and edges_row[i, j] != 0:
                G_existing.add_edge(i, j)

    components = list(nx.connected_components(G_existing))

    # If there is a single component the graph is already connected so it can terminate
    if len(components) <= 1:
        return edges_row 

    idx_to_symbol = {1: 'C', 2: 'N', 3: 'O', 4: 'F'}
    max_valence = {'C': 4, 'N': 3, 'O': 2, 'F': 1}
    bond_order = {1: 1, 2: 2, 3: 3, 4: 1.5}

    # Compute the residual chemical valence for each active atom
    remaining = {}
    for i in active:
        symbol = idx_to_symbol[nodes_row[i]]
        used = sum(bond_order.get(edges_row[i, j], 0) for j in active if j != i)
        remaining[i] = max_valence[symbol] - used

    edges_row = edges_row.copy()

    # For each pair of components, find the best possible edge (the one with the highest probability
    # between a node of the first component and a node of the second), respecting the residual valence.
    comp_list = [list(c) for c in components]
    comp_graph = nx.Graph()
    comp_graph.add_nodes_from(range(len(comp_list)))

    for a in range(len(comp_list)):
        for b in range(a + 1, len(comp_list)):
            best_prob = -1
            best_pair = None

            # Examine all possible pairs of nodes (i, j) between the two components
            for i in comp_list[a]:
                for j in comp_list[b]:

                    # Check which candidates are available based on residual value
                    budget = min(remaining[i], remaining[j])
                    candidates = [t for t, order in bond_order.items() if order <= budget]
                    if not candidates:
                        continue

                    # Among the eligible candidates, choose the one with the highest probability
                    best_type = max(candidates, key=lambda t: edge_probs_row[i, j, t])
                    p = edge_probs_row[i, j, best_type]
                    if p > best_prob:
                        best_prob = p
                        best_pair = (i, j, best_type)

            # If at least one valid pair is found, it is recorded as a possible edge between these two components in the auxiliary graph.
            if best_pair is not None:
                comp_graph.add_edge(a, b, weight=best_prob, pair=best_pair)

    # Compute the maximum spanning tree on the component graph by adding the minimum number of edges needed to
    # connect all the components, always choosing the connections with the highest probability.
    mst = nx.maximum_spanning_tree(comp_graph, weight='weight')

    # Apply the selected arcs from the spanning tree to the final matrix
    for a, b in mst.edges():
        edge_data = comp_graph.get_edge_data(a, b)
        if edge_data is None or 'pair' not in edge_data:
            continue
        i, j, best_type = edge_data['pair']
        edges_row[i, j] = best_type
        edges_row[j, i] = best_type
        remaining[i] -= bond_order[best_type]
        remaining[j] -= bond_order[best_type]

    return edges_row

# Generation of molecules
def generate_molecules(decoder, num_samples=500, dim_latent=64, device='cuda', temperature = 1.0):
    decoder.eval()

    count_fragments = 0
    count_valence = 0
    count_empty = 0

    idx_atom = {0: None, 1: 'C', 2: 'N', 3: 'O', 4: 'F'} 
    idx_edges = {
        1: Chem.BondType.SINGLE, 
        2: Chem.BondType.DOUBLE, 
        3: Chem.BondType.TRIPLE, 
        4: Chem.BondType.AROMATIC
    }

    generated = []

    with torch.no_grad():
        # Random generation of the latent vector
        z = torch.randn(num_samples, dim_latent).to(device)

        nodes_logits, edges_logits = decoder(z)
        B = z.size(0)

        # Sampling of the decoder's generated logits for node and bond, based on the temperature parameter
        nodes, _ = sample_from_logits(nodes_logits, temperature=temperature)
        nodes = nodes.cpu().numpy()

        raw_edges_sampled, edge_probs_flat = sample_from_logits(
            edges_logits.view(B, 81, 5), temperature=temperature
        )
        raw_edges = raw_edges_sampled.view(B, 9, 9).cpu().numpy()
        edge_probs_full = edge_probs_flat.view(B, 9, 9, 5).cpu().numpy()

        # Final arc matrix with padding and symmetry constraints
        edges = np.zeros((num_samples, 9, 9), dtype=np.int64)
        for b in range(num_samples):
            for i in range(9):
                for j in range(i + 1, 9):
                    if nodes[b, i] == 0 or nodes[b, j] == 0:
                        edges[b, i, j] = 0
                    else:
                        edges[b, i, j] = raw_edges[b, i, j]

            for i in range(9):
                for j in range(i + 1, 9):
                    edges[b, j, i] = edges[b, i, j]

            # Force connectivity of disconnected components, if present
            edges[b] = enforce_connectivity(nodes[b], edges[b], edge_probs_full[b])


    for mol_idx in range(num_samples):
        mol = Chem.RWMol()
        node_map = {}
        actual_idx = 0 

        # Reconstruction of the nodes
        for node in range(0, 9):
            atom_idx = nodes[mol_idx, node]
            atom_symbol = idx_atom.get(atom_idx, None)

            if atom_symbol is not None:
                atom = Chem.Atom(atom_symbol)
                mol.AddAtom(atom)
                node_map[node] = actual_idx 
                actual_idx += 1

        # Reconstruction of the arches
        for i in range(0, 9):
            for j in range(i + 1, 9):
                if i in node_map and j in node_map:
                    edge_type = edges[mol_idx, i, j]

                    if edge_type in idx_edges:
                        mol.AddBond(node_map[i], node_map[j], idx_edges[edge_type])

        try:
            # Creating the final molecule
            final_mol = mol.GetMol()
            if final_mol.GetNumAtoms() == 0:
                count_empty += 1
                continue
            
            # Track the number of fragmented molecules
            frags = Chem.GetMolFrags(final_mol, asMols=True)
            if len(frags) > 1:
                count_fragments += 1  
                continue
            
            # Final sanitization
            Chem.SanitizeMol(final_mol)
            smiles = Chem.MolToSmiles(final_mol, canonical=True)
            generated.append(smiles)

        except Exception:
            count_valence += 1
            continue
    
    print(f"Frammentate: {count_fragments}, Valenza errata: {count_valence}, Vuote: {count_empty}")
    return generated

